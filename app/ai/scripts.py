"""Fixed safety scripts and emergency contact numbers.

PLACEHOLDER: every script and number below MUST be reviewed and approved by a
qualified clinician before any real child uses this. Do not remove this marker.

These are returned verbatim to a child when their message is flagged as
"concern" or "urgent", or when a companion reply fails its safety check --
never generated by a model. The app never contacts emergency services itself;
it only shows numbers and encourages the child to reach a trusted adult.
"""

EMERGENCY_NUMBERS: dict[str, dict[str, str]] = {
    "AU": {
        "emergency": "000",
        "kids_helpline": "Kids Helpline: 1800 55 1800",
        "lifeline": "Lifeline: 13 11 14",
    },
}

DEFAULT_COUNTRY = "AU"


def get_emergency_numbers(country: str) -> dict[str, str]:
    return EMERGENCY_NUMBERS.get(country, EMERGENCY_NUMBERS[DEFAULT_COUNTRY])


def concern_script(country: str = DEFAULT_COUNTRY) -> str:
    numbers = get_emergency_numbers(country)
    return (
        "Thank you for telling me that. It sounds important. "
        "I think a trusted adult should know about this too -- like a parent, "
        "carer, or your therapist. Can you go and tell them what you just told me? "
        f"You can also talk to {numbers['kids_helpline']}, any time."
    )


def urgent_script(country: str = DEFAULT_COUNTRY) -> str:
    numbers = get_emergency_numbers(country)
    return (
        "Thank you for telling me. This is important, and you should not keep it to yourself. "
        "Please find a trusted adult right now -- a parent, carer, or teacher -- and tell them what you told me. "
        f"If you are in danger right now, call {numbers['emergency']}. "
        f"You can also call {numbers['kids_helpline']} or {numbers['lifeline']}, any time, for free."
    )


def fallback_script() -> str:
    """Used when a companion reply fails its own safety check. The child's
    message itself was not flagged -- this is just a safe, generic reply.
    """
    return "I'm here with you. Let's take a slow breath together -- in for four counts, and out for four counts."
